#!/usr/bin/env python3
"""Build the model the library embeds, from the upstream model.

The repository keeps the upstream GigaAM v3 CTC ONNX model, zstd-compressed
in volumes (models/gigaam-v3-ctc/volumes/part_NN.zst, concatenated in order).
This script, run by CMake at build time:

  1. reassembles the upstream model,
  2. applies optimize_model.py's exact rewrites,
  3. splits the result into NUM_VOLUMES volumes of equal size and compresses
     each with zstd -19, one single-threaded zstd per CPU at a time (about
     45 s per volume; the library decompresses them in parallel),
  4. writes model_volumes.h with their sizes and offsets.

Usage: build_model.py UPSTREAM_VOLUMES_DIR OUT_DIR NUM_VOLUMES
"""
import concurrent.futures
import os
import pathlib
import subprocess
import sys
import tempfile

import onnx

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import optimize_model  # noqa: E402


def zstd(args, data=None):
    return subprocess.run(["zstd", *args], input=data, stdout=subprocess.PIPE,
                          check=True).stdout


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    src, out, n = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2]), int(sys.argv[3])
    parts = sorted(src.glob("part_*.zst"))
    if not parts:
        sys.exit(f"no upstream volumes in {src}")
    upstream = b"".join(zstd(["-d", "-c", "-q", str(p)]) for p in parts)
    print(f"[build_model] upstream: {len(parts)} volumes, {len(upstream)} bytes")

    gr = optimize_model.Graph(onnx.load_from_string(upstream))
    for p in optimize_model.PASSES:
        print(f"[build_model] {p}: {getattr(optimize_model, p)(gr)} rewritten")
    gr.drop_unused_initializers()
    meta = gr.model.metadata_props.add()
    meta.key, meta.value = "nerd_dictation_gigaam_passes", ",".join(optimize_model.PASSES)
    # Serialize through a file: onnx refuses SerializeToString above 2 GB
    # anyway, and this keeps the external-data rules out of the picture.
    with tempfile.TemporaryDirectory() as tmp:
        path = pathlib.Path(tmp) / "model.onnx"
        onnx.save(gr.model, path)
        model = path.read_bytes()
    print(f"[build_model] optimized: {len(model)} bytes")

    out.mkdir(parents=True, exist_ok=True)
    size = -(-len(model) // n)
    chunks = [model[i * size:(i + 1) * size] for i in range(n)]
    if not chunks[-1]:
        sys.exit(f"model too small for {n} volumes")
    with concurrent.futures.ThreadPoolExecutor(os.cpu_count()) as pool:
        packed = list(pool.map(lambda c: zstd(["-19", "-T1", "-q", "-c"], c), chunks))
    rows = []
    for i, (chunk, data) in enumerate(zip(chunks, packed)):
        (out / f"part_{i:02d}.zst").write_bytes(data)
        rows.append((len(data), len(chunk), i * size, f"model_vol_{i:02d}"))
        print(f"[build_model] volume {i:2d}: {len(chunk)} -> {len(data)} bytes")

    lines = [
        "/* Generated by scripts/build_model.py: the embedded model's volumes. */",
        "#pragma once",
        "",
        "#include <cstddef>",
        "",
        "namespace gigaam {",
        "",
        "struct VolumeInfo {",
        "    size_t compressed_size;",
        "    size_t decompressed_size;",
        "    size_t decompressed_offset;  /* offset in the reassembled model */",
        "    const char* name;            /* res_embed resource name */",
        "};",
        "",
        f"constexpr size_t MODEL_NUM_VOLUMES = {n};",
        f"constexpr size_t MODEL_TOTAL_SIZE = {len(model)};",
        "",
        "const VolumeInfo MODEL_VOLUMES[MODEL_NUM_VOLUMES] = {",
        *[f'    {{ {c}, {d}, {o}, "{name}" }},' for c, d, o, name in rows],
        "};",
        "",
        "} /* namespace gigaam */",
        "",
    ]
    (out / "model_volumes.h").write_text("\n".join(lines))


if __name__ == "__main__":
    main()
